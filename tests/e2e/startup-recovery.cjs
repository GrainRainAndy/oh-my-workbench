const assert=require('node:assert/strict');
const {once}=require('node:events');
const {mkdirSync,readFileSync,writeFileSync,existsSync}=require('node:fs');
const {join}=require('node:path');
const {app,dialog}=require('electron');
const {DatabaseSync}=require('node:sqlite');
const {createSnapshot,activeDirectory,prepareRestore}=require('../../packages/host-core/src/persistence/backup.cjs');
const profile=join(process.env.WORKBENCH_E2E_TEMP_DIR,'startup-recovery');
mkdirSync(profile);
app.setPath('userData',profile);
const path=join(profile,'workspaces.sqlite');
const db=new DatabaseSync(path);
db.exec('CREATE TABLE workspaces(id TEXT PRIMARY KEY,revision INTEGER NOT NULL,payload TEXT NOT NULL)');
const snapshot={schemaVersion:1,id:'recover',name:'恢复的工作区',revision:1,layout:{type:'leaf',paneId:'pane'},activePaneId:'pane',views:{}};
db.prepare('INSERT INTO workspaces VALUES(?,?,?)').run(snapshot.id,1,JSON.stringify(snapshot));
db.close();
for(const name of ['plugins.sqlite','jobs.sqlite'])new DatabaseSync(join(profile,name)).close();
const backup=createSnapshot(profile);
const abandoned=prepareRestore(profile,backup.id);
const unmarked=join(profile,'stores',require('node:crypto').randomUUID());
mkdirSync(unmarked);
const damaged=Buffer.from('damaged workspace database');
const brokenBackup=createSnapshot(profile);
const brokenFile=join(profile,'backups',brokenBackup.id,'jobs.sqlite');
writeFileSync(brokenFile,damaged);
writeFileSync(path,damaged);
let prompts=0;
dialog.showMessageBox=async options=>{
  assert.equal(options.message,'无法打开本机工作区');
  assert.equal(options.buttons[2],'从已校验备份恢复');
  assert.match(options.detail,/已跳过 1 个未通过校验的备份/);
  prompts++;
  return {response:2};
};
async function verify(){
  const created=once(app,'browser-window-created');
  require('../../apps/desktop/main.cjs').startDesktop();
  const [,win]=await created;
  await once(win.webContents,'did-finish-load');
  const workspaces=await win.webContents.executeJavaScript('window.workspaces.list()');
  assert.deepEqual(workspaces,[snapshot]);
  assert.equal(prompts,1);
  assert.equal(existsSync(abandoned.directory),false);
  assert.equal(existsSync(unmarked),true);
  assert.notEqual(activeDirectory(profile),profile);
  assert.deepEqual(readFileSync(path),damaged);
  assert.deepEqual(readFileSync(brokenFile),damaged);
  console.log('Startup recovery opened the backup in a separate store and preserved the damaged database byte for byte.');
}
verify().then(()=>app.quit(),error=>{console.error(error);app.exit(1);});
